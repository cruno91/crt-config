#!/usr/bin/env python3
"""Generate the restricted 480i-only CRT EDID from the converter's original EDID.

The transformation steps are those of reference/patch-edid-crt.py, unchanged,
so the output stays byte-identical to the working converter-crt.bin. Only the
file handling differs.

Usage:
  generate-edid.py --input lontium-original.bin --output converter-crt.bin
  generate-edid.py --check     # regenerate in memory and compare with the
                               # committed converter-crt.bin (exit 1 on mismatch)
"""

import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_INPUT = os.path.join(HERE, "lontium-original.bin")
DEFAULT_OUTPUT = os.path.join(HERE, "converter-crt.bin")


class GenerateError(Exception):
    pass


def _require(condition, message):
    # Not assert: asserts vanish under python -O.
    if not condition:
        raise GenerateError(message)


def patch(source):
    edid = bytearray(source)

    _require(len(edid) == 256, "expected a 256-byte EDID (base block + one extension)")
    _require(edid[128] == 0x02, "extension block is not CTA-861")

    # Remove established timings.
    edid[35:38] = bytes(3)

    # Remove standard timings.
    edid[38:54] = b"\x01\x01" * 8

    # Remove the base block's preferred timing flag.
    edid[24] &= ~0x02

    # Preserve the monitor name descriptor.
    name = None

    for offset in range(54, 126, 18):
        descriptor = edid[offset:offset + 18]

        if descriptor[:5] == b"\x00\x00\x00\xfc\x00":
            name = bytes(descriptor)

    _require(name is not None, "no monitor name descriptor found")

    # Replace base block descriptors.
    # Avoid a base-block DTD because CTA VIC 6 carries
    # the required HDMI pixel repetition semantics.
    dummy = b"\x00\x00\x00\x10\x00" + bytes(13)

    edid[54:126] = name + dummy * 3

    # Rebuild CTA data blocks.
    blocks = bytearray()
    offset = 132
    end = 128 + edid[130]
    video_found = False

    while offset < end:
        tag = edid[offset] >> 5
        length = edid[offset] & 0x1f

        if tag == 2:
            # Advertise only VIC 6 (480i 4:3).
            # Set the native mode flag.
            if not video_found:
                blocks.extend([0x41, 0x86])
                video_found = True
        else:
            # Preserve audio, speaker allocation,
            # HDMI vendor-specific and other blocks.
            blocks.extend(edid[offset:offset + length + 1])

        offset += length + 1

    _require(video_found, "no CTA video data block found")
    _require(len(blocks) <= 123, "rebuilt CTA data blocks do not fit")

    # Remove all existing CTA detailed timings.
    edid[132:255] = bytes(123)

    # Install rebuilt CTA data blocks.
    edid[132:132 + len(blocks)] = blocks
    edid[130] = 4 + len(blocks)

    # Clear native detailed timing count.
    edid[131] &= 0xf0

    # Physical display dimensions are unknown.
    edid[21] = 0
    edid[22] = 0

    # Correct reserved digital input bits for EDID 1.3.
    edid[20] = 0x80

    # Signal sRGB chromaticities.
    edid[24] |= 0x04

    # Recalculate checksums.
    for offset in (0, 128):
        edid[offset + 127] = (
            -sum(edid[offset:offset + 127])
        ) & 0xff

    return bytes(edid)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--input", default=DEFAULT_INPUT, help="original converter EDID (default: %(default)s)")
    ap.add_argument("--output", help="where to write the restricted EDID")
    ap.add_argument("--check", action="store_true", help="compare the generated bytes with --expected")
    ap.add_argument("--expected", default=DEFAULT_OUTPUT, help="file to compare against with --check")
    args = ap.parse_args(argv)

    with open(args.input, "rb") as fh:
        source = fh.read()
    try:
        out = patch(source)
    except GenerateError as exc:
        print("generate-edid: %s" % exc, file=sys.stderr)
        return 2
    digest = hashlib.sha256(out).hexdigest()

    if args.check:
        with open(args.expected, "rb") as fh:
            expected = fh.read()
        if out != expected:
            print("generate-edid: MISMATCH: generated %s, expected %s" % (digest, hashlib.sha256(expected).hexdigest()), file=sys.stderr)
            return 1
        print("generate-edid: OK: %s reproduces %s (sha256 %s)" % (os.path.basename(args.input), os.path.basename(args.expected), digest))
        return 0

    if not args.output:
        ap.error("--output is required unless --check is given")
    with open(args.output, "wb") as fh:
        fh.write(out)
    print("Created %s (sha256 %s)" % (args.output, digest))
    return 0


if __name__ == "__main__":
    sys.exit(main())
